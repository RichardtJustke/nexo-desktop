# Topo: o Nex à esquerda, o nome e o que dá para fazer à direita
draw_header() {
  local f="$1" i start=$(( $1 * NEX_H ))
  for (( i = 0; i < NEX_H; i++ )); do
    case $i in
      5) printf ' %s   %sNEXO para Linux%s\033[K\n' "${NEX_FRAMES[$((start + i))]}" "$BOLD" "$NC" ;;
      6) printf ' %s   %s%s%s\033[K\n' "${NEX_FRAMES[$((start + i))]}" "$DIM" "$HEADER_SUB" "$NC" ;;
      *) printf ' %s\033[K\n' "${NEX_FRAMES[$((start + i))]}" ;;
    esac
  done
}

# Ao abrir, a animação roda uma vez e o Nex fica parado
header() {
  local f
  HEADER_SUB="$1"
  if [ "$FANCY" != 1 ]; then
    echo "NEXO para Linux - $1"
    echo ""
    return
  fi
  echo ""
  printf '\033[?25l'
  draw_header 0
  if [ "$ASK" = 1 ]; then
    for (( f = 1; f < NEX_N; f++ )); do
      sleep 0.11
      printf '\033[%dA' "$NEX_H"
      draw_header "$f"
    done
    sleep 0.11
    printf '\033[%dA' "$NEX_H"
    draw_header 0
  fi
  printf '\033[?25h'
  echo ""
}

