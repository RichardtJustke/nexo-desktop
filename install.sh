# Para a rodinha: grava a versão mais nova no arquivo $1
latest_tag_into() { latest_tag >"$1"; }

latest_tag() {
  local tag
  tag=$(curl -s "https://api.github.com/repos/${GITHUB_REPO}/releases/latest" 2>/dev/null | grep -oP '"tag_name":\s*"\K[^"]+' || true)
  if [ -z "$tag" ]; then
    tag=$(curl -s "https://api.github.com/repos/${GITHUB_REPO}/tags" 2>/dev/null | grep -oP '"name":\s*"\K[^"]+' | head -n 1 || true)
  fi
  echo "$tag"
}

# Endereço de um arquivo da versão, pelo final do nome (ex.: "_amd64.deb")
asset_url() {
  curl -s "https://api.github.com/repos/${GITHUB_REPO}/releases/tags/$1" \
    | grep -oP '"browser_download_url":\s*"\K[^"]+' \
    | grep -F -- "$2" | head -n 1
}

# Versão instalada. Não roda o "nexo --version": ele abre o app em vez de responder.
installed_version() {
  local v=""
  if command -v dpkg-query >/dev/null 2>&1; then
    v=$(dpkg-query -W -f='${Version}' nexo 2>/dev/null || true)
  fi
  [ -z "$v" ] && [ -f "$VERSION_FILE" ] && v=$(cat "$VERSION_FILE")
  [ -z "$v" ] && command -v "$BINARY_NAME" >/dev/null 2>&1 && v="sim (versão desconhecida)"
  echo "$v"
}

