  fi
  if ! run "Instalando o pacote" deb_install "$tmp"; then
    fail "A instalação do pacote falhou. Detalhes em $LOG_FILE"
    exit 1
  fi
  rm -f "$tmp"
  ok "Instalado pelo pacote Debian"
}

install_appimage() {
  local tag="$1" arch="$2" dir="$3" url other="x86_64" bin
  [ "$arch" = "arm64" ] && other="aarch64"
  bin="${dir}/${BINARY_NAME}"
  # O Tauri nomeia o AppImage com amd64/aarch64 (ex.: Nexo_0.1.0_amd64.AppImage); x86_64 fica de reserva
  url=$(asset_url "$tag" "_${arch}.AppImage")
  [ -z "$url" ] && url=$(asset_url "$tag" "_${other}.AppImage")
  mkdir -p "$dir"
  # Baixa ao lado e troca no fim: com o Nexo aberto, escrever direto no arquivo falha ("Text file busy")
  if [ -z "$url" ] || ! download "$url" "${bin}.new"; then
    rm -f "${bin}.new"
    fail "Não deu para baixar o NEXO $tag para $other."
    exit 1
  fi
  mv -f "${bin}.new" "$bin"
  chmod +x "$bin"
  ok "Instalado em ${DIM}$(tilde "$bin")${NC}"
  desktop_entry "$bin" "$dir"
}

desktop_entry() {
  local bin="$1" dir="$2" apps="${HOME}/.local/share/applications" icons="${HOME}/.local/share/icons/hicolor/512x512/apps"
  if [ "$dir" = "/usr/local/bin" ] || [ "$(id -u)" -eq 0 ]; then
    apps="/usr/share/applications"
    icons="/usr/share/icons/hicolor/512x512/apps"
  fi
  mkdir -p "$apps" "$icons"
  curl -fsSL -o "${icons}/nexo.png" "https://raw.githubusercontent.com/${GITHUB_REPO}/main/assets/icon.png" 2>/dev/null || true
  cat <<EOF >"${apps}/nexo.desktop"
[Desktop Entry]
Name=Nexo
GenericName=Produtividade & Gestão
Comment=Sistema Integrado de Produtividade, Finanças e Hábitos
Exec=${bin} %U
Icon=nexo
Terminal=false
Type=Application
Categories=Office;Utility;ProjectManagement;
StartupWMClass=Nexo
EOF
  chmod +x "${apps}/nexo.desktop"
  command -v update-desktop-database >/dev/null 2>&1 && update-desktop-database "$apps" 2>/dev/null || true
  ok "Atalho no menu de aplicativos"
}

do_install() {
  local format="$1" dest="$2" interactive="$3" arch tag current
  arch=$(detect_arch)
  ok "Sistema ${DIM}$(distro_name) ($arch)${NC}"

  local tmp="${TMPDIR:-/tmp}/nexo-tag.$$"
  run "Procurando a versão mais nova" latest_tag_into "$tmp" || true
  tag=$(cat "$tmp" 2>/dev/null || true)
  rm -f "$tmp"
  if [ -z "$tag" ]; then
    tag="v0.1.0"
    warn "Não deu para consultar o GitHub. Tentando ${tag}."
  else
    current=$(installed_version)
    if [ "$current" = "$tag" ]; then
      ok "Versão mais nova ${DIM}${tag} (você já tem esta; vou reinstalar)${NC}"
    else
      ok "Versão mais nova ${DIM}${tag}${NC}"
    fi
  fi

  if [ "$format" = "auto" ]; then
    if is_debian; then
      if [ "$interactive" = 1 ]; then
        menu "Como instalar?" "Pacote .deb (pede a sua senha)" "AppImage (sem senha, em ~/.local/bin)"
        [ "$CHOICE" = 1 ] && format="deb" || format="appimage"
      else
        format="deb"
      fi
    else
      format="appimage"
    fi
  fi

  if [ "$format" = "deb" ]; then
    install_deb "$tag" "$arch"
  else
    install_appimage "$tag" "$arch" "$dest"
  fi
  mkdir -p "$(dirname "$VERSION_FILE")" && echo "$tag" >"$VERSION_FILE"

  echo ""
  printf ' %sPronto!%s Abra o NEXO pelo menu de aplicativos ou digite %s%s%s no terminal.\n' "$BOLD" "$NC" "$LILAC" "$BINARY_NAME" "$NC"
  if [ "$format" != "deb" ] && [[ ":$PATH:" != *":$dest:"* ]]; then
    note "Para o comando '$BINARY_NAME' funcionar, ponha no ~/.bashrc ou ~/.zshrc:"
    local shown="$dest"
    [ "${dest#"$HOME"}" != "$dest" ] && shown="\$HOME${dest#"$HOME"}"
    note "export PATH=\"\$PATH:${shown}\""
  fi
  echo ""
}

# ------------------------------------------------------------------------------
# Remover e versão
# ------------------------------------------------------------------------------
do_uninstall() {
  local interactive="$1"
  if [ "$interactive" = 1 ]; then
    menu "Remover o NEXO deste computador?" "Não, deixar como está" "Sim, remover"
    if [ "$CHOICE" != 2 ]; then
      ok "Nada foi removido."
      return
    fi
  fi
  rm -f "${HOME}/.local/bin/${BINARY_NAME}" "${HOME}/.local/share/applications/nexo.desktop" \
    "${HOME}/.local/share/icons/hicolor/512x512/apps/nexo.png" "$VERSION_FILE"
  if command -v dpkg >/dev/null 2>&1 && dpkg -s nexo >/dev/null 2>&1; then
    [ "$(id -u)" -eq 0 ] || sudo -v
    run "Removendo o pacote Debian" deb_remove || true
  fi
  if [ -f "/usr/local/bin/${BINARY_NAME}" ]; then
    as_root rm -f "/usr/local/bin/${BINARY_NAME}" "/usr/share/applications/nexo.desktop" 2>/dev/null || true
  fi
  ok "NEXO removido deste computador"
  note "Sua conta e seus dados continuam guardados: é só entrar de novo."
  echo ""
}

do_version() {
  local current latest
  current=$(installed_version)
  local tmp="${TMPDIR:-/tmp}/nexo-tag.$$"
  run "Procurando a versão mais nova" latest_tag_into "$tmp" || true
  latest=$(cat "$tmp" 2>/dev/null || true)
  rm -f "$tmp"
  ok "Instalada ${DIM}${current:-nenhuma}${NC}"
  ok "Mais nova ${DIM}${latest:-não deu para consultar}${NC}"
  if [ -n "$current" ] && [ -n "$latest" ] && [ "$current" != "$latest" ] && [[ "$current" != sim* ]]; then
    note "Para atualizar: rode de novo e escolha Instalar ou atualizar."
  fi
  echo ""
}

show_help() {
  echo "NEXO para Linux"
  echo ""
  echo "Uso: install.sh [comando] [opções]   (sem nada, num terminal: abre o menu)"
  echo ""
  echo "Comandos:"
  echo "  install, update    Instala ou atualiza para a versão mais nova (padrão)"
  echo "  uninstall          Remove o NEXO e o atalho (a conta e os dados ficam)"
  echo "  version, -v        Mostra a versão instalada e a mais nova"
  echo "  help, -h           Mostra esta ajuda"
  echo ""
  echo "Opções:"
  echo "  --deb | --appimage        Escolhe o tipo de pacote (ou --format deb|appimage)"
  echo "  --dest <pasta>            Onde pôr o AppImage (padrão: ~/.local/bin)"
  echo "  --system                  Instala em /usr/local/bin (pede sudo)"
  exit 0
}

# ------------------------------------------------------------------------------
main() {
  local action="" format="auto" dest="${HOME}/.local/bin" interactive=0
  [ $# -eq 0 ] && [ "$ASK" = 1 ] && interactive=1

  while [ $# -gt 0 ]; do
    case "$1" in
      install | update) action="install" ;;
      uninstall) action="uninstall" ;;
      version | -v | --version) action="version" ;;
      help | -h | --help) show_help ;;
      --deb) format="deb" ;;
      --appimage) format="appimage" ;;
      --format) shift; format="$1" ;;
      --dest) shift; dest="$1" ;;
      --system) dest="/usr/local/bin" ;;
      *) fail "Argumento desconhecido: $1"; show_help ;;
    esac
    shift
  done

  : >"$LOG_FILE" 2>/dev/null || LOG_FILE=/dev/null

  if [ "$interactive" = 1 ]; then
    header "instalar · atualizar · remover"
    menu "O que você quer fazer?" "Instalar ou atualizar" "Remover" "Ver a versão" "Sair"
    case "$CHOICE" in
      1) action="install" ;;
      2) action="uninstall" ;;
      3) action="version" ;;
      4) ok "Até a próxima!"; exit 0 ;;
    esac
  else
    action="${action:-install}"
    case "$action" in
      install) header "instalando" ;;
      uninstall) header "removendo" ;;
      version) header "versão" ;;
    esac
  fi

  case "$action" in
    install) do_install "$format" "$dest" "$interactive" ;;
    uninstall) do_uninstall "$interactive" ;;
    version) do_version ;;
  esac
}

main "$@"
