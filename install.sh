# Roda um comando com a rodinha ao lado do texto. A saída vai para o $LOG_FILE (mostrado se der erro).
run() {
  local label="$1" pid i=0 status
  shift
  if [ "$FANCY" != 1 ]; then
    echo " - $label..."
    "$@" >>"$LOG_FILE" 2>&1
    return $?
  fi
  printf '\033[?25l'
  "$@" >>"$LOG_FILE" 2>&1 &
  pid=$!
  while kill -0 "$pid" 2>/dev/null; do
    printf '\r\033[K %s%s%s %s' "$LILAC" "${SPIN[$i]}" "$NC" "$label"
    i=$(( (i + 1) % ${#SPIN[@]} ))
    sleep 0.08
  done
  status=0
  wait "$pid" || status=$?
  printf '\r\033[K\033[?25h'
  return "$status"
}

# Caminho com ~ no lugar da pasta pessoal, só para mostrar
tilde() { local p="$1"; [ "${p#"$HOME"}" != "$p" ] && p="~${p#"$HOME"}"; echo "$p"; }

mb() { awk -v b="$1" 'BEGIN { printf "%.0f", b / 1048576 }'; }

# Baixa $1 para $2 mostrando a barra. Devolve o código do curl.
download() {
  local url="$1" dest="$2" total pid i=0 have pct width=24 filled bar status
  rm -f "$dest"
  if [ "$FANCY" != 1 ]; then
    echo " - Baixando..."
    curl -fL --progress-bar -o "$dest" "$url"
    return $?
  fi
  total=$(curl -sIL "$url" 2>/dev/null | tr -d '\r' | awk 'tolower($1) == "content-length:" { v = $2 } END { print v + 0 }')
  printf '\033[?25l'
  curl -fsSL -o "$dest" "$url" 2>>"$LOG_FILE" &
  pid=$!
  while kill -0 "$pid" 2>/dev/null; do
    have=$(stat -c %s "$dest" 2>/dev/null || echo 0)
    if [ "${total:-0}" -gt 0 ]; then
      pct=$(( have * 100 / total ))
      [ "$pct" -gt 100 ] && pct=100
      filled=$(( pct * width / 100 ))
      bar="${LILAC}$(printf '%*s' "$filled" '' | sed 's/ /━/g')${TRACK}$(printf '%*s' $(( width - filled )) '' | sed 's/ /━/g')${NC}"
      printf '\r\033[K %s%s%s Baixando  %s  %3d%%  %s%s/%s MB%s' "$LILAC" "${SPIN[$i]}" "$NC" "$bar" "$pct" "$DIM" "$(mb "$have")" "$(mb "$total")" "$NC"
    else
      printf '\r\033[K %s%s%s Baixando  %s%s MB%s' "$LILAC" "${SPIN[$i]}" "$NC" "$DIM" "$(mb "$have")" "$NC"
    fi
    i=$(( (i + 1) % ${#SPIN[@]} ))
    sleep 0.08
  done
  status=0
  wait "$pid" || status=$?
  printf '\r\033[K\033[?25h'
  if [ "$status" -eq 0 ]; then
    ok "Baixado ${DIM}($(mb "$(stat -c %s "$dest" 2>/dev/null || echo 0)") MB)${NC}"
  fi
  return "$status"
}

# ------------------------------------------------------------------------------
# Menu: setas (ou j/k) e Enter; número também vale. Responde em $CHOICE (1, 2, 3...).
# ------------------------------------------------------------------------------
menu() {
  local question="$1" sel=1 n key rest i
  shift
  local opts=("$@")
  n=${#opts[@]}

  # Sem cores: pergunta com números
  if [ "$FANCY" != 1 ]; then
    echo "$question"
    for i in "${!opts[@]}"; do echo "  $((i + 1))) ${opts[$i]}"; done
    while true; do
      printf '> '
      read -r key < /dev/tty || key=""
      key="${key:-1}"
      if [[ "$key" =~ ^[0-9]+$ ]] && [ "$key" -ge 1 ] && [ "$key" -le "$n" ]; then
        CHOICE="$key"
        return 0
      fi
    done
  fi

  printf '\033[?25l'
  printf ' %s?%s %s%s%s\n' "$LILAC" "$NC" "$BOLD" "$question" "$NC"
  while true; do
    for (( i = 0; i < n; i++ )); do
      if [ $(( i + 1 )) -eq "$sel" ]; then
        printf '\033[K   %s❯ %s%s\n' "$LILAC" "${opts[$i]}" "$NC"
      else
        printf '\033[K     %s%s%s\n' "$DIM" "${opts[$i]}" "$NC"
      fi
    done
    printf '\033[K   %s↑↓ escolher · Enter confirmar%s\n' "$DIM" "$NC"

    IFS= read -rsn1 key < /dev/tty || key=""
    if [ "$key" = $'\033' ]; then
      IFS= read -rsn2 -t 0.05 rest < /dev/tty || rest=""
      key="$key$rest"
    fi
    case "$key" in
      $'\033[A' | k | K) sel=$(( sel > 1 ? sel - 1 : n )) ;;
      $'\033[B' | j | J) sel=$(( sel < n ? sel + 1 : 1 )) ;;
      [1-9]) [ "$key" -le "$n" ] && sel="$key" ;;
      "") break ;;
      q | Q) printf '\033[%dA\033[J' $(( n + 2 )); printf '\033[?25h'; ok "Até a próxima!"; exit 0 ;;
    esac
    printf '\033[%dA' $(( n + 1 ))
  done

  # Fecha o menu numa linha só com a resposta
  printf '\033[%dA\033[J' $(( n + 2 ))
  printf '\033[?25h'
  ok "$question ${DIM}${opts[$((sel - 1))]}${NC}"
  CHOICE="$sel"
}

